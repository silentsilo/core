//! A silo's backup kept in a directory: a NAS share, an external drive, or
//! a folder a consumer sync client already syncs. Two devices writing here
//! never write the same file, which is the case sync clients handle well.
//! The asymmetry with putting a *silo* in such a folder: that shares one
//! snapshot file and produces conflict copies; sharing the log converges.

use std::io::{Read, Write};
use std::path::{Component, Path, PathBuf};
use std::sync::Arc;
use std::sync::atomic::{AtomicBool, Ordering};

use async_trait::async_trait;

use crate::{ObjectStore, Progress, StoreError, StoredObject};

/// How much moves between two reports. Small enough that a bar on a slow
/// drive moves smoothly, large enough that the per-chunk bookkeeping costs
/// nothing next to the copy itself.
const CHUNK: usize = 512 * 1024;

pub struct FolderStore {
    root: PathBuf,
    /// Set for iCloud Drive: what starts the download of a file that is
    /// there only as a placeholder (see `crate::icloud`).
    placeholders: Option<fn(&Path) -> bool>,
}

/// How long a read waits for iCloud to bring a file down before saying so.
const DOWNLOAD_WAIT: std::time::Duration = std::time::Duration::from_secs(60);

impl FolderStore {
    pub fn new(root: PathBuf) -> Self {
        Self {
            root,
            placeholders: None,
        }
    }

    /// A folder iCloud Drive keeps, where a file not downloaded yet is
    /// `.<name>.icloud` (macOS 13 and earlier, iOS 16 and earlier). Listings
    /// show it under its own name and a read starts the download with
    /// `start` and waits for it.
    pub(crate) fn with_placeholders(root: PathBuf, start: fn(&Path) -> bool) -> Self {
        Self {
            root,
            placeholders: Some(start),
        }
    }

    /// Resolves a key to a path inside the root, refusing anything that
    /// climbs out of it.
    ///
    /// Keys are generated by this app and none of them contain `..` — but
    /// this is the one backend where a bad key becomes a write anywhere on
    /// the user's disk, so it is checked rather than assumed. A symbolic
    /// link or a junction inside the root that points out of it is refused
    /// the same way: whoever can write to a shared folder could plant one.
    fn path_for(&self, key: &str) -> Result<PathBuf, StoreError> {
        self.reachable()?;
        let relative = PathBuf::from(key.replace('\\', "/"));
        if relative
            .components()
            .any(|c| !matches!(c, Component::Normal(_)))
        {
            return Err(StoreError::Other(format!("refusing unsafe key: {key}")));
        }
        let path = self.root.join(relative);
        self.stays_inside(&path, key)?;
        Ok(path)
    }

    /// Whether `path`, followed through every link on the way, is still in
    /// the root. Asked of the deepest part of it that exists: what does not
    /// exist yet is created where its parent really is.
    fn stays_inside(&self, path: &Path, key: &str) -> Result<(), StoreError> {
        let root = std::fs::canonicalize(&self.root).map_err(|e| Self::map_io(e, key))?;
        let mut probe = path;
        loop {
            match std::fs::canonicalize(probe) {
                Ok(real) if real.starts_with(&root) => return Ok(()),
                Ok(_) => {
                    return Err(StoreError::Denied(format!(
                        "{key} leads out of the folder through a link"
                    )));
                }
                Err(_) => match probe.parent() {
                    Some(parent) if parent.starts_with(&self.root) => probe = parent,
                    _ => return Ok(()),
                },
            }
        }
    }

    /// A key that names a regular file, or a refusal: a FIFO or a device
    /// would hang a read or return what is not an object.
    fn regular_file(path: &Path, key: &str) -> Result<u64, StoreError> {
        let meta = std::fs::metadata(path).map_err(|e| Self::map_io(e, key))?;
        if meta.is_file() {
            Ok(meta.len())
        } else {
            Err(StoreError::NotFound(key.to_string()))
        }
    }

    /// Brings down a file iCloud keeps only as a placeholder, before a read.
    /// Nothing to do for a file that is here, or one that is not there at
    /// all, which the read then reports as missing.
    async fn download(&self, path: &Path, key: &str) -> Result<(), StoreError> {
        let Some(start) = self.placeholders else {
            return Ok(());
        };
        let placeholder = placeholder_for(path);
        if path.exists() || !placeholder.is_file() {
            return Ok(());
        }
        start(path);
        let until = std::time::Instant::now() + DOWNLOAD_WAIT;
        while std::time::Instant::now() < until {
            tokio::time::sleep(std::time::Duration::from_millis(250)).await;
            if path.is_file() && !placeholder.exists() {
                return Ok(());
            }
        }
        Err(StoreError::Unreachable(silentsilo_core::coded::coded_with(
            "err.icloud_downloading",
            format!("iCloud Drive is still downloading {key}. Try again in a moment."),
            &[("key", &key)],
        )))
    }

    /// A missing root is a drive that is not plugged in, for every call. A
    /// read would take it for an empty copy and a write would recreate it
    /// and start filling it as one.
    fn reachable(&self) -> Result<(), StoreError> {
        if self.root.is_dir() {
            Ok(())
        } else {
            Err(StoreError::Unreachable(format!(
                "{} is not available",
                self.root.display()
            )))
        }
    }

    fn map_io(err: std::io::Error, what: &str) -> StoreError {
        match err.kind() {
            std::io::ErrorKind::NotFound => StoreError::NotFound(what.to_string()),
            std::io::ErrorKind::PermissionDenied => StoreError::Denied(err.to_string()),
            _ => StoreError::Other(err.to_string()),
        }
    }
}

#[async_trait]
impl ObjectStore for FolderStore {
    async fn put(&self, key: &str, body: Vec<u8>) -> Result<(), StoreError> {
        let path = self.path_for(key)?;
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent).map_err(|e| Self::map_io(e, key))?;
        }

        // Written beside the target and renamed into place. A sync client
        // watching this folder must never see a half-written object — it
        // would upload the fragment, and another device would fetch bytes
        // that decrypt to nothing. Synced before the rename: a record is
        // marked delivered the moment this returns, and on a drive someone
        // then unplugs, renamed-but-unwritten is the same as lost.
        let temp = temp_beside(&path);
        {
            let mut file = std::fs::File::create(&temp).map_err(|e| Self::map_io(e, key))?;
            file.write_all(&body).map_err(|e| Self::map_io(e, key))?;
            file.sync_all().map_err(|e| Self::map_io(e, key))?;
        }
        silentsilo_core::rename_with_retry(&temp, &path).map_err(|e| Self::map_io(e, key))?;
        Ok(())
    }

    async fn put_from_file(&self, key: &str, source: &Path) -> Result<(), StoreError> {
        let path = self.path_for(key)?;
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent).map_err(|e| Self::map_io(e, key))?;
        }
        let temp = temp_beside(&path);
        std::fs::copy(source, &temp).map_err(|e| Self::map_io(e, key))?;
        // Reopened with write access: Windows refuses to flush a read-only
        // handle.
        let copied = std::fs::OpenOptions::new()
            .write(true)
            .open(&temp)
            .map_err(|e| Self::map_io(e, key))?;
        copied.sync_all().map_err(|e| Self::map_io(e, key))?;
        silentsilo_core::rename_with_retry(&temp, &path).map_err(|e| Self::map_io(e, key))?;
        Ok(())
    }

    async fn copy(&self, from: &str, to: &str) -> Result<(), StoreError> {
        let source = self.path_for(from)?;
        self.download(&source, from).await?;
        Self::regular_file(&source, from)?;
        self.put_from_file(to, &source).await
    }

    async fn get_to_file(&self, key: &str, dest: &Path) -> Result<(), StoreError> {
        let source = self.path_for(key)?;
        self.download(&source, key).await?;
        Self::regular_file(&source, key)?;
        std::fs::copy(source, dest)
            .map(|_| ())
            .map_err(|e| Self::map_io(e, key))
    }

    async fn put_from_file_reporting(
        &self,
        key: &str,
        source: &Path,
        progress: Progress<'_>,
    ) -> Result<(), StoreError> {
        let path = self.path_for(key)?;
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent).map_err(|e| Self::map_io(e, key))?;
        }
        // Same temp-then-sync-then-rename as `put_from_file`, so a stopped
        // copy leaves the key exactly as it was rather than half of it.
        let temp = temp_beside(&path);
        if let Err(e) = copy_watched(source.to_path_buf(), temp.clone(), true, key, progress).await
        {
            let _ = std::fs::remove_file(&temp);
            return Err(e);
        }
        silentsilo_core::rename_with_retry(&temp, &path).map_err(|e| Self::map_io(e, key))
    }

    async fn get_to_file_reporting(
        &self,
        key: &str,
        dest: &Path,
        progress: Progress<'_>,
    ) -> Result<(), StoreError> {
        let source = self.path_for(key)?;
        self.download(&source, key).await?;
        Self::regular_file(&source, key)?;
        if let Err(e) = copy_watched(source, dest.to_path_buf(), false, key, progress).await {
            // A partial file left where a caller expects an object reads as
            // content that decrypts to nothing.
            let _ = std::fs::remove_file(dest);
            return Err(e);
        }
        Ok(())
    }

    async fn get(&self, key: &str) -> Result<Vec<u8>, StoreError> {
        let path = self.path_for(key)?;
        self.download(&path, key).await?;
        Self::regular_file(&path, key)?;
        std::fs::read(path).map_err(|e| Self::map_io(e, key))
    }

    async fn get_prefix(&self, key: &str, len: u64) -> Result<Vec<u8>, StoreError> {
        use std::io::Read;
        let path = self.path_for(key)?;
        self.download(&path, key).await?;
        Self::regular_file(&path, key)?;
        let file = std::fs::File::open(&path).map_err(|e| Self::map_io(e, key))?;
        let mut out = Vec::new();
        file.take(len)
            .read_to_end(&mut out)
            .map_err(|e| Self::map_io(e, key))?;
        Ok(out)
    }

    /// A placeholder answers with the size it records, without a download;
    /// one that records none is brought down to be measured.
    async fn head(&self, key: &str) -> Result<Option<i64>, StoreError> {
        let path = self.path_for(key)?;
        if self.placeholders.is_some() && !path.exists() {
            if let Some(size) = std::fs::read(placeholder_for(&path))
                .ok()
                .and_then(|plist| placeholder_size(&plist))
            {
                return Ok(Some(size));
            }
            self.download(&path, key).await?;
        }
        match std::fs::metadata(&path) {
            Ok(meta) if meta.is_file() => Ok(Some(meta.len() as i64)),
            // Not an object: a FIFO, a device, a directory.
            Ok(_) => Ok(None),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
            Err(e) => Err(Self::map_io(e, key)),
        }
    }

    async fn delete(&self, key: &str) -> Result<(), StoreError> {
        let path = self.path_for(key)?;
        // A file iCloud has not downloaded is deleted through its
        // placeholder, which stands for it there.
        if self.placeholders.is_some() {
            match std::fs::remove_file(placeholder_for(&path)) {
                Err(e) if e.kind() != std::io::ErrorKind::NotFound => {
                    return Err(Self::map_io(e, key));
                }
                _ => {}
            }
        }
        match std::fs::remove_file(path) {
            Ok(()) => Ok(()),
            // Deleting something already gone is the desired end state, and
            // callers use this to clean up after failures.
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(()),
            Err(e) => Err(Self::map_io(e, key)),
        }
    }

    async fn list(&self, prefix: &str) -> Result<Vec<StoredObject>, StoreError> {
        // A missing prefix is an empty listing; a missing root is refused
        // by `path_for`.
        let base = self.path_for(prefix.trim_end_matches('/'))?;
        let mut out = Vec::new();
        let mut seen = std::collections::HashSet::new();
        let walk = Walk {
            root: &self.root,
            real_root: std::fs::canonicalize(&self.root).map_err(|e| Self::map_io(e, prefix))?,
            placeholders: self.placeholders.is_some(),
        };
        walk.collect(&base, &mut out, &mut seen)?;
        // Callers depend on this being ordered: operation keys are the
        // Lamport counter zero-padded, so sorting by key is sorting by time.
        // A filesystem promises nothing about readdir order.
        out.sort_by(|a, b| a.key.cmp(&b.key));
        Ok(out)
    }

    fn describe(&self) -> String {
        self.root.display().to_string()
    }

    /// The one call that creates the root: the user is adding or testing
    /// this place, so a folder not made yet is expected, where during a
    /// pass it means the drive is gone.
    async fn check(&self) -> Result<(), StoreError> {
        std::fs::create_dir_all(&self.root).map_err(|e| Self::map_io(e, "the folder"))?;
        crate::probe(self).await
    }
}

/// Copies a file chunk by chunk, telling the caller how far it has got
/// while it runs and stopping where it is when the caller says to.
///
/// The copy itself is blocking `std::fs`, and on a multi-gigabyte file it
/// would hold an async worker for minutes, so it runs on a blocking thread.
/// What crosses back is a byte count per chunk over a channel of one: the
/// callback belongs to the caller's thread, and a channel that small keeps
/// the two within a chunk of each other, so a stop lands on the next one.
async fn copy_watched(
    source: PathBuf,
    dest: PathBuf,
    flush: bool,
    key: &str,
    progress: Progress<'_>,
) -> Result<(), StoreError> {
    let stop = Arc::new(AtomicBool::new(false));
    let halt = stop.clone();
    let (tx, mut rx) = tokio::sync::mpsc::channel::<u64>(1);

    let copy = tokio::task::spawn_blocking(move || -> std::io::Result<()> {
        let mut input = std::fs::File::open(&source)?;
        // Created only once the source opened, so a missing object leaves no
        // empty file behind.
        let mut output = std::fs::File::create(&dest)?;
        let mut buf = vec![0u8; CHUNK];
        loop {
            if halt.load(Ordering::Relaxed) {
                return Err(std::io::Error::new(
                    std::io::ErrorKind::Interrupted,
                    "stopped",
                ));
            }
            let read = input.read(&mut buf)?;
            if read == 0 {
                break;
            }
            output.write_all(&buf[..read])?;
            // A closed receiver means the caller is gone; the copy still
            // finishes rather than failing over a lost progress report.
            let _ = tx.blocking_send(read as u64);
        }
        if flush {
            output.sync_all()?;
        }
        Ok(())
    });

    // Drains until the copy drops its sender, which is the copy ending.
    while let Some(moved) = rx.recv().await {
        if progress(moved).is_break() {
            stop.store(true, Ordering::Relaxed);
        }
    }

    match copy.await {
        Ok(Ok(())) if stop.load(Ordering::Relaxed) => Err(StoreError::Cancelled),
        Ok(Ok(())) => Ok(()),
        Ok(Err(_)) if stop.load(Ordering::Relaxed) => Err(StoreError::Cancelled),
        Ok(Err(e)) => Err(FolderStore::map_io(e, key)),
        Err(e) => Err(StoreError::Other(e.to_string())),
    }
}

/// The temporary name a write goes to before its rename, always ending in
/// `.part` so listings can skip it, and unique to this write: two writers of
/// one key at once, such as two devices on a synced folder, must not rename
/// each other's half-written file away.
fn temp_beside(path: &Path) -> PathBuf {
    path.with_extension(format!(
        "{}.{}.part",
        path.extension().and_then(|e| e.to_str()).unwrap_or("tmp"),
        uuid::Uuid::new_v4().simple()
    ))
}

/// Where iCloud keeps a file it has not downloaded: `.<name>.icloud` beside
/// where the file will be.
fn placeholder_for(path: &Path) -> PathBuf {
    let name = path
        .file_name()
        .map(|n| n.to_string_lossy().into_owned())
        .unwrap_or_default();
    path.with_file_name(format!(".{name}.icloud"))
}

/// The name of the file a placeholder stands for, when `name` is one.
fn placeholder_target(name: &std::ffi::OsStr) -> Option<String> {
    let name = name.to_str()?;
    let target = name.strip_prefix('.')?.strip_suffix(".icloud")?;
    (!target.is_empty()).then(|| target.to_string())
}

/// The size a placeholder records (`NSURLFileSizeKey` in its binary
/// property list), read without asking iCloud for anything. `None` for
/// anything this does not recognise, which then costs a download.
fn placeholder_size(plist: &[u8]) -> Option<i64> {
    if plist.len() < 8 + 32 || !plist.starts_with(b"bplist00") {
        return None;
    }
    let trailer = &plist[plist.len() - 32..];
    let offset_width = usize::from(trailer[6]);
    let ref_width = usize::from(trailer[7]);
    let count = usize::try_from(be(&trailer[8..16])?).ok()?;
    let top = usize::try_from(be(&trailer[16..24])?).ok()?;
    let table = usize::try_from(be(&trailer[24..32])?).ok()?;
    let object = |index: usize| -> Option<&[u8]> {
        if index >= count {
            return None;
        }
        let at = table.checked_add(index.checked_mul(offset_width)?)?;
        let offset = usize::try_from(be(plist.get(at..at.checked_add(offset_width)?)?)?).ok()?;
        plist.get(offset..)
    };

    let dict = object(top)?;
    if dict.first()? >> 4 != 0xD {
        return None;
    }
    let (entries, refs) = plist_length(dict)?;
    let reference = |i: usize| -> Option<usize> {
        let start = i.checked_mul(ref_width)?;
        usize::try_from(be(refs.get(start..start.checked_add(ref_width)?)?)?).ok()
    };
    for i in 0..entries {
        if plist_ascii(object(reference(i)?)?) == Some("NSURLFileSizeKey") {
            return plist_int(object(reference(entries.checked_add(i)?)?)?);
        }
    }
    None
}

/// A big-endian unsigned integer of one to eight bytes.
fn be(bytes: &[u8]) -> Option<u64> {
    if bytes.is_empty() || bytes.len() > 8 {
        return None;
    }
    Some(bytes.iter().fold(0, |n, b| (n << 8) | u64::from(*b)))
}

/// An object's count from its marker, and what follows the marker.
fn plist_length(object: &[u8]) -> Option<(usize, &[u8])> {
    let low = usize::from(object.first()? & 0x0F);
    if low != 0x0F {
        return Some((low, object.get(1..)?));
    }
    let marker = *object.get(1)?;
    if marker >> 4 != 0x1 {
        return None;
    }
    let width = 1usize << (marker & 0x0F);
    let n = usize::try_from(be(object.get(2..2 + width)?)?).ok()?;
    Some((n, object.get(2 + width..)?))
}

fn plist_int(object: &[u8]) -> Option<i64> {
    let marker = *object.first()?;
    if marker >> 4 != 0x1 {
        return None;
    }
    let width = 1usize << (marker & 0x0F);
    i64::try_from(be(object.get(1..1 + width)?)?).ok()
}

fn plist_ascii(object: &[u8]) -> Option<&str> {
    if object.first()? >> 4 != 0x5 {
        return None;
    }
    let (n, body) = plist_length(object)?;
    std::str::from_utf8(body.get(..n)?).ok()
}

/// One listing's walk through the folder.
struct Walk<'a> {
    root: &'a Path,
    /// The root with every link resolved, which a link must stay under.
    real_root: PathBuf,
    /// iCloud Drive: placeholders are listed as the files they stand for.
    placeholders: bool,
}

impl Walk<'_> {
    fn collect(
        &self,
        dir: &Path,
        out: &mut Vec<StoredObject>,
        seen: &mut std::collections::HashSet<PathBuf>,
    ) -> Result<(), StoreError> {
        // A target is a directory the user chose, and it is theirs: it may
        // hold a symlink or a junction pointing back at an ancestor.
        // Descending only into directories not seen before keeps a listing
        // from walking in a circle until the stack runs out.
        //
        // A path that will not canonicalise is left to `read_dir` below
        // rather than treated as empty. "Could not look" and "looked and
        // found nothing" are the two answers it would be worst to confuse
        // here: a caller that reads an unreachable target as holding nothing
        // carries on and silently misses records.
        if let Ok(real) = std::fs::canonicalize(dir)
            && (!real.starts_with(&self.real_root) || !seen.insert(real))
        {
            return Ok(());
        }

        let entries = match std::fs::read_dir(dir) {
            Ok(entries) => entries,
            // An absent prefix is an empty listing, not a failure: it is the
            // normal state of a bucket nothing has been written to yet.
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(()),
            Err(e) => return Err(FolderStore::map_io(e, &dir.display().to_string())),
        };

        for entry in entries.flatten() {
            let path = entry.path();
            let Ok(mut kind) = entry.file_type() else {
                continue;
            };
            // A link is followed only where it stays inside the root: one
            // planted to point at the rest of the disk lists nothing.
            if kind.is_symlink() {
                match std::fs::canonicalize(&path) {
                    Ok(real) if real.starts_with(&self.real_root) => {
                        match std::fs::metadata(&path) {
                            Ok(meta) => kind = meta.file_type(),
                            Err(_) => continue,
                        }
                    }
                    _ => continue,
                }
            }
            if kind.is_dir() {
                self.collect(&path, out, seen)?;
                continue;
            }
            // Only regular files are objects. A FIFO or a device would hang
            // the read that follows or hand back something that is not one.
            if !kind.is_file() {
                continue;
            }
            let Ok(relative) = path.strip_prefix(self.root) else {
                continue;
            };
            let mut relative = relative.to_path_buf();
            let mut size = std::fs::metadata(&path)
                .map(|m| m.len() as i64)
                .unwrap_or(0);
            if self.placeholders
                && let Some(target) = placeholder_target(&entry.file_name())
            {
                // Downloaded already: listed under its own name.
                if path.with_file_name(&target).exists() {
                    continue;
                }
                relative.set_file_name(&target);
                size = std::fs::read(&path)
                    .ok()
                    .and_then(|plist| placeholder_size(&plist))
                    .unwrap_or(0);
            }
            // A rename that never completed, or a sync client's own scratch.
            // Reporting it as an object would hand the caller a partial file.
            if relative.extension().and_then(|e| e.to_str()) == Some("part") {
                continue;
            }
            out.push(StoredObject {
                key: relative.to_string_lossy().replace('\\', "/"),
                size,
            });
        }
        Ok(())
    }
}

